#!/bin/bash
#
#  Cross-compile cosmo's Android native dependencies (arm64-v8a) into deps/prefix:
#    pixman, freetype, cairo (Artboard's Cairo render adapter) and LibRaw (RAW decode).
#  These are the platform libraries the NDK does not ship; the arstro C++ (Artboard
#  core, ImageProcessing engine, cosmo core) is cross-compiled by the app CMake, not here.
#
#  Usage:  ./build_deps.sh [all|pixman|freetype|cairo|libraw|crossfile]
#  Idempotent: each stage skips if its lib is already present (rm -rf build/<stage> to force).
#
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
source "$HERE/env.sh"

DL="$HERE/downloads"; BUILD="$HERE/build"; PREFIX="$ANDROID_PREFIX"
mkdir -p "$BUILD" "$PREFIX"
NPROC="$(nproc)"

gen_crossfile() {
  cat > "$HERE/android-arm64.cross" <<EOF
# GENERATED by build_deps.sh — meson cross file for arm64-v8a Android (API $ANDROID_API)
[binaries]
c = '$CC'
cpp = '$CXX'
ar = '$AR'
strip = '$STRIP'
ranlib = '$RANLIB'
pkg-config = 'pkg-config'

[built-in options]
default_library = 'static'
prefix = '$PREFIX'

[properties]
# NOTE: do NOT set sys_root — our deps live at absolute paths outside the NDK
# sysroot, and sys_root would make pkg-config wrongly prefix them. The clang
# wrapper (aarch64-linux-android<API>-clang) already targets the right sysroot.
pkg_config_libdir = '$PREFIX/lib/pkgconfig'

[host_machine]
system = 'android'
cpu_family = 'aarch64'
cpu = 'aarch64'
endian = 'little'
EOF
  echo "wrote $HERE/android-arm64.cross"
}

build_pixman() {
  [ -f "$PREFIX/lib/libpixman-1.a" ] && { echo "pixman: already built"; return; }
  echo "== pixman =="
  rm -rf "$BUILD/pixman"; mkdir -p "$BUILD/pixman"
  tar -xf "$DL/pixman-0.42.2.tar.gz" -C "$BUILD/pixman" --strip-components=1
  ( cd "$BUILD/pixman" && meson setup _b --cross-file "$HERE/android-arm64.cross" \
      --prefix="$PREFIX" --default-library=static --buildtype=release \
      -Dgtk=disabled -Dlibpng=disabled -Dtests=disabled -Da64-neon=disabled \
    && meson compile -C _b -j"$NPROC" && meson install -C _b )
  echo "pixman: OK"
}

build_freetype() {
  [ -f "$PREFIX/lib/libfreetype.a" ] && { echo "freetype: already built"; return; }
  echo "== freetype =="
  rm -rf "$BUILD/freetype"; mkdir -p "$BUILD/freetype"
  tar -xf "$DL/freetype-2.13.2.tar.xz" -C "$BUILD/freetype" --strip-components=1
  # CMake cross via the NDK toolchain file; strip optional deps (no png/zlib/harfbuzz/brotli).
  ( cd "$BUILD/freetype" && cmake -S . -B _b -G Ninja \
      -DCMAKE_TOOLCHAIN_FILE="$NDK_HOME/build/cmake/android.toolchain.cmake" \
      -DANDROID_ABI="$ANDROID_ABI" -DANDROID_PLATFORM="android-$ANDROID_API" \
      -DCMAKE_INSTALL_PREFIX="$PREFIX" -DBUILD_SHARED_LIBS=OFF \
      -DFT_DISABLE_HARFBUZZ=ON -DFT_DISABLE_PNG=ON -DFT_DISABLE_BROTLI=ON \
      -DFT_DISABLE_BZIP2=ON -DFT_DISABLE_ZLIB=ON \
    && cmake --build _b -j"$NPROC" && cmake --install _b )
  echo "freetype: OK"
}

build_cairo() {
  [ -f "$PREFIX/lib/libcairo.a" ] && { echo "cairo: already built"; return; }
  echo "== cairo =="
  rm -rf "$BUILD/cairo"; mkdir -p "$BUILD/cairo"
  tar -xf "$DL/cairo-1.18.2.tar.xz" -C "$BUILD/cairo" --strip-components=1
  # cairo 1.18.2 uses FT_Color / FT_Palette_* (COLR-v1 colour fonts) but never
  # includes the FreeType colour header, so the FT_Color prototype in
  # cairo-ft-private.h fails to compile. Inject FT_COLOR_H right after FT_FREETYPE_H
  # in the shared cairo-ft.h (available since FreeType 2.10; we ship 2.13.2).
  sed -i 's|^#include FT_FREETYPE_H|#include FT_FREETYPE_H\n#include FT_COLOR_H|' \
      "$BUILD/cairo/src/cairo-ft.h"
  # Minimal image + FreeType font backend only. No fontconfig (the Android host injects
  # cairo_ft font faces directly), no png/zlib/glib/X/tests.
  ( cd "$BUILD/cairo" && meson setup _b --cross-file "$HERE/android-arm64.cross" \
      --prefix="$PREFIX" --default-library=static --buildtype=release --wrap-mode=nodownload \
      -Dfreetype=enabled -Dfontconfig=disabled -Dpng=disabled -Dzlib=disabled \
      -Dglib=disabled -Dxlib=disabled -Dxcb=disabled -Dtee=disabled -Dtests=disabled \
      -Dquartz=disabled -Ddwrite=disabled -Dspectre=disabled -Dsymbol-lookup=disabled \
    && meson compile -C _b -j"$NPROC" && meson install -C _b )
  echo "cairo: OK"
}

build_libraw() {
  [ -f "$PREFIX/lib/libraw.a" ] && { echo "libraw: already built"; return; }
  echo "== libraw (arm64) =="
  local LR="$HERE/../../../ImageProcessing/lib/LibRaw"
  [ -f "$LR/libraw/libraw.h" ] || { echo "libraw source missing at $LR"; return 1; }
  # Build OUT OF TREE: the vendored LibRaw already holds x86_64 objects + lib/libraw.a
  # from the desktop build, which must not be clobbered. Copy the sources, headers and
  # Makefile.dist into deps/build and cross-compile the static lib there with the NDK
  # compiler (zlib from the NDK sysroot; no libjpeg/LCMS — core RAW decoders only).
  local B="$BUILD/libraw"
  rm -rf "$B"; mkdir -p "$B/object" "$B/lib"
  cp -r "$LR/src" "$LR/libraw" "$LR/internal" "$LR/Makefile.dist" "$B/"
  [ -d "$LR/GoPro" ] && cp -r "$LR/GoPro" "$B/"   # some decoders #include "GoPro/..."
  ( cd "$B" && make -f Makefile.dist lib/libraw.a -j"$NPROC" \
       CXX="$CXX" \
       CFLAGS="-O2 -I. -w -DUSE_ZLIB -fPIC -std=c++17" )
  cp "$B/lib/libraw.a" "$PREFIX/lib/"
  mkdir -p "$PREFIX/include/libraw"
  cp "$LR"/libraw/*.h "$PREFIX/include/libraw/"
  echo "libraw: OK"
}

case "${1:-all}" in
  crossfile) gen_crossfile ;;
  pixman)    gen_crossfile; build_pixman ;;
  freetype)  build_freetype ;;
  cairo)     gen_crossfile; build_cairo ;;
  libraw)    build_libraw ;;
  all)       gen_crossfile; build_pixman; build_freetype; build_cairo; build_libraw ;;
  *) echo "usage: $0 [all|pixman|freetype|cairo|libraw|crossfile]"; exit 1 ;;
esac
echo "done: $1"

/*
 *  interstellar_web_tokens — the web UI's design tokens, printed FROM app/Theme.h (R-SVC-4; cosmo's
 *  cosmo_web_tokens and Solaris's solaris_web_tokens are the worked examples).
 *
 *  The web face must look like the window, and two hand-kept palettes are the first thing that makes
 *  two faces look different (Theme.h: "a forked token file is a divergence with a delay fuse"). So the
 *  stylesheet's tokens are GENERATED: Interstellar's accent is installed exactly as the window
 *  installs it (`installInterstellarAccent`, #CF5AED), then the same inline token functions every
 *  widget calls — cosmo's palette, Interstellar's own surfaces, the shell metrics, the radii, the
 *  faces, the motion durations — are printed as CSS custom properties. apps/interstellar/web/css/
 *  tokens.css is the committed output; ctest `interstellar_web_tokens_current` fails when Theme.h
 *  moves and it was not regenerated:
 *
 *      build/apps/interstellar/cli/interstellar_web_tokens > apps/interstellar/web/css/tokens.css
 */
#include "Theme.h"
#include <cmath>
#include <cstdio>

using namespace arstro::interstellar_v1;
using artboard::Color;

namespace
{
    int byte(double v) { return (int)std::lround(std::fmax(0.0, std::fmin(1.0, v)) * 255.0); }

    void colour(const char *name, const Color &c)
    {
        if (c.a >= 0.9995)
            std::printf("  --%s: #%02X%02X%02X;\n", name, byte(c.r), byte(c.g), byte(c.b));
        else
            std::printf("  --%s: rgba(%d, %d, %d, %g);\n", name, byte(c.r), byte(c.g), byte(c.b), c.a);
    }

    void rgb(const char *name, const Color &c) { std::printf("  --%s-rgb: %d, %d, %d;\n", name, byte(c.r), byte(c.g), byte(c.b)); }
    void ms(const char *name, double v) { std::printf("  --%s: %gms;\n", name, v); }
    void px(const char *name, double v) { std::printf("  --%s: %gpx;\n", name, v); }
}

int main()
{
    installInterstellarAccent(); // the window's first call (R-UI-2): every accent-derived token follows it
    std::printf("/* GENERATED by interstellar_web_tokens from apps/interstellar/app/Theme.h (cosmo's palette, Interstellar's\n"
                "   purple-pink) - do not edit. Regenerate: interstellar_web_tokens > apps/interstellar/web/css/tokens.css\n"
                "   (ctest interstellar_web_tokens_current). */\n"
                ":root {\n");
    // cosmo's palette, through Interstellar's aliases
    colour("background", palette::background());
    colour("foreground", palette::foreground());
    colour("card", palette::card());
    colour("popover", palette::popover());
    colour("primary", palette::primary());
    colour("primary-foreground", palette::primaryForeground());
    colour("secondary", palette::secondary());
    colour("secondary-foreground", palette::secondaryForeground());
    colour("muted", palette::muted());
    colour("muted-foreground", palette::mutedForeground());
    colour("destructive", palette::destructive());
    colour("success", palette::success());
    colour("border", palette::border());
    colour("input", palette::input());
    colour("ring", palette::ring());
    colour("white", palette::white());
    rgb("white", palette::white());
    rgb("primary", palette::primary());
    colour("hover-wash", palette::hoverWash(1.0));
    // Interstellar's own surfaces (Theme.h `surface`): the monitor, the deck, the timeline
    colour("monitor-bg", surface::monitorBg());
    colour("deck-bg", surface::deckBg());
    colour("ruler-bg", surface::rulerBg());
    colour("track-header-bg", surface::trackHeaderBg());
    colour("lane-bg", surface::laneBg());
    colour("lane-alt-bg", surface::laneAltBg());
    colour("clip-video", surface::clipVideo());
    colour("clip-audio", surface::clipAudio());
    colour("thumb-placeholder", surface::thumbPlaceholder());
    colour("skeleton", surface::skeleton());
    colour("playhead", surface::playhead());
    colour("marker", surface::marker());
    // radius:: and the spacing ladder
    px("radius-hairline", radius::hairline());
    px("radius-control", radius::control());
    px("radius-pill", radius::pill());
    px("space-pad-x", space::padX());
    px("space-gap", space::gap());
    px("space-row-h", space::rowH());
    px("space-bar-h", space::barH());
    px("space-indent", space::indent());
    // the shell's fixed metrics: the timeline's time origin, its ruler and track heights, the columns
    px("shell-top-bar-h", shell::topBarH());
    px("shell-right-w", shell::rightW());
    px("shell-left-w", shell::leftW());
    px("shell-transport-h", shell::transportH());
    px("shell-header-w", shell::headerWidth());
    px("shell-ruler-h", shell::rulerH());
    px("shell-track-h", shell::trackH());
    // font:: — the family names (base.css maps them to the files `ntwb install` ships)
    std::printf("  --font-sans: \"%s\";\n", font::sans());
    std::printf("  --font-sans-medium: \"%s\";\n", font::sansMedium());
    std::printf("  --font-sans-semibold: \"%s\";\n", font::sansSemiBold());
    std::printf("  --font-mono: \"%s\";\n", font::mono());
    std::printf("  --font-mono-medium: \"%s\";\n", font::monoMedium());
    // motion:: — the durations the window eases with (design rule §2.5)
    ms("motion-hover", motion::kHoverMs);
    ms("motion-dissolve", motion::kDissolveMs);
    ms("motion-scroll", motion::kScrollMs);
    ms("motion-cross-fade", motion::kCrossFadeMs);
    ms("motion-select", motion::kSelectMs);
    ms("motion-slide", motion::kSlideMs);
    ms("motion-catch-up", motion::kCatchUpMs);
    ms("motion-zoom", motion::kZoomMs);
    ms("motion-reflow", motion::kReflowMs);
    ms("motion-screen-fade", motion::kScreenFadeMs);
    ms("motion-progress-in", motion::kProgressInMs);
    ms("motion-progress-out", motion::kProgressOutMs);
    std::printf("}\n");
    return 0;
}

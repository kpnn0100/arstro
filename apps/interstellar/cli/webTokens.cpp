/*
 *  interstellar_web_tokens — the web UI's design tokens, printed FROM app/Theme.h (R-SVC-4; cosmo's
 *  cosmo_web_tokens and Solaris's solaris_web_tokens are the worked examples).
 *
 *  The web face must look like the window, and two hand-kept palettes are the first thing that makes
 *  two faces look different (Theme.h: "a forked token file is a divergence with a delay fuse"). So the
 *  stylesheet's tokens are GENERATED: Interstellar's accent is installed exactly as the window
 *  installs it (`installInterstellarAccent`, #CF5AED), then EVERY token function Theme.h reaches —
 *  cosmo's palette / radius / font / metrics through Interstellar's aliases, and Interstellar's own
 *  space / motion / surface / shell — is printed as a CSS custom property, so a widget module never
 *  needs a token that is not here (and never edits this file). The names:
 *
 *      palette::canvasBg()        --canvas-bg          (cosmo's names: the borrowed ui/* read them)
 *      palette::whiteAlpha(a)     --white-rgb          (parametric: rgba(var(--white-rgb), a))
 *      palette::primaryAlpha(a)   --primary-rgb,  palette::successAlpha(a)  --success-rgb
 *      palette::hoverWash(t)      --hover-wash         (= hoverWash(1); a fraction t is whiteAlpha(0.07 t))
 *      radius::control()          --radius-control     metrics::anchorHitRadius()  --anchor-hit-radius
 *      font::sansMedium()         --font-sans-medium   (the family names base.css registers)
 *      space::padX()              --space-pad-x        space::u(n) = n × --space-u
 *      motion::kModalOpenMs       --motion-modal-open  (every k…Ms, "k" and "Ms" dropped)
 *      surface::monitorBg()       --monitor-bg         surface::scrim(a)  --scrim-rgb
 *      shell::topBarH()           --shell-top-bar-h    shell::deckH(H) = clamp(--shell-deck-min,
 *                                                       H × --shell-deck-ratio, --shell-deck-max)
 *
 *  apps/interstellar/web/css/tokens.css is the committed output; ctest
 *  `interstellar_web_tokens_current` fails when Theme.h moves and it was not regenerated:
 *
 *      build/apps/interstellar/cli/interstellar_web_tokens > apps/interstellar/web/css/tokens.css
 */
#include "Theme.h"
#include <cmath>
#include <cstdio>

using namespace arstro::interstellar_v1;
using artboard::Color;

namespace
{
    int byte(double v) { return (int)std::lround(std::fmax(0.0, std::fmin(1.0, v)) * 255.0); }

    void colour(const char *name, const Color &c)
    {
        if (c.a >= 0.9995)
            std::printf("  --%s: #%02X%02X%02X;\n", name, byte(c.r), byte(c.g), byte(c.b));
        else
            std::printf("  --%s: rgba(%d, %d, %d, %g);\n", name, byte(c.r), byte(c.g), byte(c.b), c.a);
    }

    /** "r, g, b" of a colour, for the parametric tokens (primaryAlpha(a) -> rgba(var(--primary-rgb), a)). */
    void rgb(const char *name, const Color &c) { std::printf("  --%s-rgb: %d, %d, %d;\n", name, byte(c.r), byte(c.g), byte(c.b)); }
    void ms(const char *name, double v) { std::printf("  --motion-%s: %gms;\n", name, v); }
    void px(const char *name, double v) { std::printf("  --%s: %gpx;\n", name, v); }
    void str(const char *name, const char *v) { std::printf("  --%s: \"%s\";\n", name, v); }
    void number(const char *name, double v) { std::printf("  --%s: %g;\n", name, v); }
}

int main()
{
    installInterstellarAccent(); // the window's first call (R-UI-2): every accent-derived token follows it
    std::printf("/* GENERATED by interstellar_web_tokens from apps/interstellar/app/Theme.h (cosmo's palette, Interstellar's\n"
                "   purple-pink) - do not edit. Regenerate: interstellar_web_tokens > apps/interstellar/web/css/tokens.css\n"
                "   (ctest interstellar_web_tokens_current). The names: apps/interstellar/cli/webTokens.cpp. */\n"
                ":root {\n");
    // ── palette:: (cosmo's, aliased) — theme.css tokens, then the per-surface literals ──
    colour("background", palette::background());
    colour("foreground", palette::foreground());
    colour("card", palette::card());
    colour("popover", palette::popover());
    colour("primary", palette::primary());
    colour("primary-foreground", palette::primaryForeground());
    colour("secondary", palette::secondary());
    colour("secondary-foreground", palette::secondaryForeground());
    colour("muted", palette::muted());
    colour("muted-foreground", palette::mutedForeground());
    colour("destructive", palette::destructive());
    colour("success", palette::success());
    colour("border", palette::border());
    colour("input", palette::input());
    colour("input-light", palette::inputLight());
    colour("input-light-text", palette::inputLightText());
    colour("switch-background", palette::switchBackground());
    colour("ring", palette::ring());
    colour("canvas-bg", palette::canvasBg());
    colour("histogram-bg", palette::histogramBg());
    colour("left-rail-bg", palette::leftRailBg());
    colour("filmstrip-bg", palette::filmstripBg());
    colour("folder-chip-bg", palette::folderChipBg());
    colour("segmented-bg", palette::segmentedBg());
    colour("curve-plot-bg", palette::curvePlotBg());
    colour("white", palette::white());
    // parametric: whiteAlpha(a), primaryAlpha(a), successAlpha(a); hoverWash(t) = whiteAlpha(0.07 t)
    rgb("white", palette::white());
    rgb("primary", palette::primary());
    rgb("success", palette::success());
    rgb("destructive", palette::destructive());
    rgb("foreground", palette::foreground());
    colour("hover-wash", palette::hoverWash(1.0));
    number("contrast", palette::contrast());   // the runtime high-contrast amount: Interstellar never moves it
    // ── radius:: and metrics:: (cosmo's) ──
    px("radius-hairline", radius::hairline());
    px("radius-control", radius::control());
    px("radius-pill", radius::pill());
    px("anchor-hit-radius", metrics::anchorHitRadius());
    // ── font:: — the family names (base.css registers the files `ntwb install` ships under them) ──
    str("font-sans", font::sans());
    str("font-sans-medium", font::sansMedium());
    str("font-sans-semibold", font::sansSemiBold());
    str("font-mono", font::mono());
    str("font-mono-medium", font::monoMedium());
    // ── space:: — cosmo's 3.25 px ladder and Home's 8/16/32 rhythm ──
    px("space-u", space::u(1));
    px("space-pad-x", space::padX());
    px("space-gap", space::gap());
    px("space-row-h", space::rowH());
    px("space-bar-h", space::barH());
    px("space-indent", space::indent());
    px("space-home8", space::home8());
    px("space-home16", space::home16());
    px("space-home32", space::home32());
    // ── motion:: — every duration the window eases with (design rule §2.5) ──
    ms("hover", motion::kHoverMs);
    ms("modal-open", motion::kModalOpenMs);
    ms("modal-close", motion::kModalCloseMs);
    ms("dropdown", motion::kDropdownMs);
    ms("dissolve", motion::kDissolveMs);
    ms("scroll", motion::kScrollMs);
    ms("cross-fade", motion::kCrossFadeMs);
    ms("select", motion::kSelectMs);
    ms("slide", motion::kSlideMs);
    ms("catch-up", motion::kCatchUpMs);
    ms("zoom", motion::kZoomMs);
    ms("reflow", motion::kReflowMs);
    ms("screen-fade", motion::kScreenFadeMs);
    ms("progress-in", motion::kProgressInMs);
    ms("progress-out", motion::kProgressOutMs);
    ms("pulse", motion::kPulseMs);
    // ── surface:: — Interstellar's own: the monitor, the deck, the timeline ──
    colour("monitor-bg", surface::monitorBg());
    colour("deck-bg", surface::deckBg());
    colour("ruler-bg", surface::rulerBg());
    colour("track-header-bg", surface::trackHeaderBg());
    colour("lane-bg", surface::laneBg());
    colour("lane-alt-bg", surface::laneAltBg());
    colour("clip-video", surface::clipVideo());
    colour("clip-audio", surface::clipAudio());
    colour("thumb-placeholder", surface::thumbPlaceholder());
    colour("skeleton", surface::skeleton());
    rgb("scrim", surface::scrim(1.0));   // scrim(a) = rgba(var(--scrim-rgb), a)
    colour("playhead", surface::playhead());
    colour("marker", surface::marker());
    // ── shell:: — the fixed metrics more than one widget reads ──
    px("shell-top-bar-h", shell::topBarH());
    px("shell-right-w", shell::rightW());
    px("shell-left-w", shell::leftW());
    px("shell-transport-h", shell::transportH());
    px("shell-header-w", shell::headerWidth());
    px("shell-ruler-h", shell::rulerH());
    px("shell-track-h", shell::trackH());
    px("shell-wheel-notch", shell::wheelNotchPx());
    px("shell-min-monitor-w", shell::minMonitorW());
    px("shell-min-monitor-h", shell::minMonitorH());
    {
        // deckH(H) is a clamp of a fraction of the window height: its three numbers, read back from it
        const double lo = shell::deckH(0.0), hi = shell::deckH(1e9);
        double ratio = 0.0;
        for (double h = 1.0; h < 1e5 && ratio == 0.0; h += 1.0)
        {
            const double d = shell::deckH(h);
            if (d > lo && d < hi) ratio = d / h;
        }
        px("shell-deck-min", lo);
        px("shell-deck-max", hi);
        number("shell-deck-ratio", ratio);
    }
    std::printf("}\n");
    return 0;
}
